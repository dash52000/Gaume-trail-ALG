export function icon(name) {
  return raw(`<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[name] || ""}</svg>`);
}

export function avatar(profile, size = 24) {
  const name = profile?.displayName || "?";
  return html`<span class="avatar" style="${raw(`background:${couleur(profile?.avatarColorHex)};width:${size}px;height:${size}px;font-size:${Math.round(size * 0.45)}px`)}">${initiale(name)}</span>`;
}

/** Remplace le contenu d'un élément. */
export function render(el, content) {
  el.innerHTML = String(content);
}
